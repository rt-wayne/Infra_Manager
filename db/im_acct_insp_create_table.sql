-- ===== INDEX IND_IM_ACCT_REQ_04
-- 【不得改名】程式依此索引名稱判斷「同帳號已有申請在處理中」：唯一鍵違反的錯誤訊息
-- 中出現「.IND_IM_ACCT_REQ_04)」才回 409 E07（RequestService.IDX_IN_FLIGHT），
-- 其他唯一鍵衝突回 500。不得改名；也不得改成一般唯一約束——「只限在途單唯一」
-- 的條件式唯一只能用這種函數式索引表達，改成 ACCT_ID 直接唯一會連已結案的
-- 申請單都擋住，同一帳號就再也不能送第二張申請。
-- 作用：同一帳號在途（REVIEW／EXEC／VERIFY）申請單最多一筆；結案的不佔用。
CREATE UNIQUE INDEX IND_IM_ACCT_REQ_04 ON IM_ACCT_REQ (CASE REQ_STATE_CODE WHEN 'REVIEW' THEN ACCT_ID WHEN 'EXEC' THEN ACCT_ID WHEN 'VERIFY' THEN ACCT_ID END) ;

