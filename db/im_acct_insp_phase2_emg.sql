-- ===== INDEX（三個；已存在就略過）
DECLARE
  v_cnt NUMBER;
  PROCEDURE create_index(p_name VARCHAR2, p_ddl VARCHAR2) IS
  BEGIN
    SELECT COUNT(*) INTO v_cnt FROM USER_INDEXES WHERE INDEX_NAME = p_name;
    IF v_cnt = 0 THEN
      EXECUTE IMMEDIATE p_ddl;
      DBMS_OUTPUT.PUT_LINE(p_name || ' 已建立');
    ELSE
      DBMS_OUTPUT.PUT_LINE(p_name || ' 已存在，略過');
    END IF;
  END;
BEGIN
  -- 「只看自己的單」與依送出時間排序（同 IND_IM_ACCT_REQ_03 寫法）
  create_index('IND_IM_EMG_ACCESS_01',
    'CREATE INDEX IND_IM_EMG_ACCESS_01 ON IM_EMG_ACCESS (APPLY_BY, SUBMIT_DATE)');
  -- 排程 J03 與首頁卡：DECIDE_CODE 為空的列靠 DUE_DATE NOT NULL 仍進索引
  create_index('IND_IM_EMG_ACCESS_02',
    'CREATE INDEX IND_IM_EMG_ACCESS_02 ON IM_EMG_ACCESS (DECIDE_CODE, DUE_DATE)');
  -- 由帳號反查被哪些緊急存取單影響（EMG_ID 是 PK 首欄，不另建）
  create_index('IND_IM_EMG_AFFECT_ACCT_01',
    'CREATE INDEX IND_IM_EMG_AFFECT_ACCT_01 ON IM_EMG_AFFECT_ACCT (ACCT_ID)');
END;
