CREATE TABLE IM_FLOW (
    FLOW_ID             VARCHAR2(32)    NOT NULL,
    FLOW_NAME           VARCHAR2(100 CHAR) NOT NULL,
    FLOW_DESC           VARCHAR2(500 CHAR),
    DOC_TYPE            VARCHAR2(20)    NOT NULL,
    IS_DFLT             NUMBER(1)       DEFAULT 0 NOT NULL,
    STATUS              NUMBER(1)       DEFAULT 1 NOT NULL,
    CREATE_DATE         DATE            DEFAULT SYSDATE NOT NULL,
    CREATE_BY           VARCHAR2(30)    NOT NULL,
    UPDATE_DATE         DATE,
    UPDATE_BY           VARCHAR2(30),
    CONSTRAINT PK_IM_FLOW          PRIMARY KEY (FLOW_ID),
    CONSTRAINT CK_IM_FLOW_DOC_TYPE CHECK (DOC_TYPE IN ('CR', 'ACCOUNT', 'INSPECTION')),
    CONSTRAINT CK_IM_FLOW_IS_DFLT  CHECK (IS_DFLT IN (0, 1)),
    CONSTRAINT CK_IM_FLOW_DFLT_ON  CHECK (IS_DFLT = 0 OR STATUS = 1),
    CONSTRAINT CK_IM_FLOW_STATUS   CHECK (STATUS IN (0, 1))
);

-- 同一文件類型只能有一個預設流程（函式型唯一索引，只對 IS_DFLT = 1 的列生效）
CREATE UNIQUE INDEX IND_IM_FLOW_01 ON IM_FLOW (CASE WHEN IS_DFLT = 1 THEN DOC_TYPE END);

COMMENT ON TABLE  IM_FLOW IS '簽核流程主檔。目的：定義各文件類型可用的簽核流程。來源：舊系統 workflows.json 預載 4 筆＋後台維護。主鍵：FLOW_ID';
COMMENT ON COLUMN IM_FLOW.FLOW_ID     IS '流程鍵值：full／p2_high／p1_emergency／imported（沿用舊系統值）';
COMMENT ON COLUMN IM_FLOW.FLOW_NAME   IS '流程名稱';
COMMENT ON COLUMN IM_FLOW.FLOW_DESC   IS '流程說明';
COMMENT ON COLUMN IM_FLOW.DOC_TYPE    IS '適用文件類型：CR 設備異動申請／ACCOUNT 帳號申請（預留）／INSPECTION 巡檢（預留）';
COMMENT ON COLUMN IM_FLOW.IS_DFLT     IS '是否該文件類型預設流程：1 是／0 否，default 0；每類型至多一個，且預設流程必須啟用';
COMMENT ON COLUMN IM_FLOW.STATUS      IS '狀態：1 啟用／0 停用（停用流程不可被新單選用，既有單據不受影響），default 1';
COMMENT ON COLUMN IM_FLOW.CREATE_DATE IS '建立時間，default SYSDATE';
COMMENT ON COLUMN IM_FLOW.CREATE_BY   IS '建立人員工號';
COMMENT ON COLUMN IM_FLOW.UPDATE_DATE IS '最後更新時間';
COMMENT ON COLUMN IM_FLOW.UPDATE_BY   IS '最後更新人員工號';


CREATE TABLE IM_FLOW_STEP (
    FLOW_STEP_ID        NUMBER(19)      GENERATED BY DEFAULT ON NULL AS IDENTITY,
    FLOW_ID             VARCHAR2(32)    NOT NULL,
    SEQ_NO              NUMBER(5)       NOT NULL,
    STEP_CODE           VARCHAR2(30)    NOT NULL,
    STEP_NAME           VARCHAR2(50 CHAR) NOT NULL,
    APPR_TYPE           VARCHAR2(10)    NOT NULL,
    USER_ID             VARCHAR2(30),
    ROLE_ID             VARCHAR2(32),
    IS_NOTIFY_ONLY      NUMBER(1)       DEFAULT 0 NOT NULL,
    IS_ALLOW_DELEG      NUMBER(1)       DEFAULT 0 NOT NULL,
    STEP_MODE_CODE      VARCHAR2(20)    DEFAULT 'SEQUENTIAL' NOT NULL,
    STATUS              NUMBER(1)       DEFAULT 1 NOT NULL,
    CREATE_DATE         DATE            DEFAULT SYSDATE NOT NULL,
    CREATE_BY           VARCHAR2(30)    NOT NULL,
    UPDATE_DATE         DATE,
    UPDATE_BY           VARCHAR2(30),
    CONSTRAINT PK_IM_FLOW_STEP             PRIMARY KEY (FLOW_STEP_ID),
    CONSTRAINT CK_IM_FLOW_STEP_APPR_TYPE   CHECK (APPR_TYPE IN ('USER', 'ROLE')),
    CONSTRAINT CK_IM_FLOW_STEP_APPR_TARGET CHECK (
        (APPR_TYPE = 'USER' AND USER_ID IS NOT NULL AND ROLE_ID IS NULL) OR
        (APPR_TYPE = 'ROLE' AND ROLE_ID IS NOT NULL AND USER_ID IS NULL)),
    CONSTRAINT CK_IM_FLOW_STEP_NOTIFY      CHECK (IS_NOTIFY_ONLY IN (0, 1)),
    CONSTRAINT CK_IM_FLOW_STEP_DELEG       CHECK (IS_ALLOW_DELEG IN (0, 1)),
    CONSTRAINT CK_IM_FLOW_STEP_MODE        CHECK (STEP_MODE_CODE IN ('SEQUENTIAL', 'POST_HOC')),
    CONSTRAINT CK_IM_FLOW_STEP_STATUS      CHECK (STATUS IN (0, 1))
);

-- 同一流程內「啟用中」的關卡順序不得重複；停用（STATUS 0）的舊版關卡不受此限。
-- 唯一索引在每個 DML 當下即檢查，修改流程時須於同一交易內先將舊列 STATUS 改 0，
-- 再新增同 SEQ_NO 的新列（順序顛倒會 ORA-00001）
CREATE UNIQUE INDEX IND_IM_FLOW_STEP_01 ON IM_FLOW_STEP (
    CASE WHEN STATUS = 1 THEN FLOW_ID END,
    CASE WHEN STATUS = 1 THEN SEQ_NO  END);

COMMENT ON TABLE  IM_FLOW_STEP IS '簽核流程關卡定義。目的：每個流程的關卡順序與簽核對象。來源：舊系統 workflows.json 預載＋後台維護。主鍵：FLOW_STEP_ID。關卡名稱只存於本表，簽核實例以 FLOW_STEP_ID 參照；修改流程時應於同一交易內先停用舊列（STATUS 0）再新增關卡列，不得改寫已被簽核實例參照的列';
COMMENT ON COLUMN IM_FLOW_STEP.FLOW_STEP_ID   IS '流水號（identity 自動產生）';
COMMENT ON COLUMN IM_FLOW_STEP.FLOW_ID        IS '所屬流程，參照 IM_FLOW.FLOW_ID';
COMMENT ON COLUMN IM_FLOW_STEP.SEQ_NO         IS '關卡順序（1 起）';
COMMENT ON COLUMN IM_FLOW_STEP.STEP_CODE      IS '關卡代碼（沿用舊系統 key：dept_manager／governance_review／idc_admin／it_manager／governance_final），供程式判斷關卡性質';
COMMENT ON COLUMN IM_FLOW_STEP.STEP_NAME      IS '關卡顯示名稱';
COMMENT ON COLUMN IM_FLOW_STEP.APPR_TYPE      IS '簽核對象類型：USER 指定人員／ROLE 角色池';
COMMENT ON COLUMN IM_FLOW_STEP.USER_ID        IS 'APPR_TYPE = USER 時的簽核人工號，參照 IM_USER.USER_ID';
COMMENT ON COLUMN IM_FLOW_STEP.ROLE_ID        IS 'APPR_TYPE = ROLE 時的簽核角色，參照 IM_ROLE.ROLE_ID';
COMMENT ON COLUMN IM_FLOW_STEP.IS_NOTIFY_ONLY IS '是否僅通知不簽核：1 是／0 否，default 0';
COMMENT ON COLUMN IM_FLOW_STEP.IS_ALLOW_DELEG IS '是否允許代簽：1 是／0 否，default 0';
COMMENT ON COLUMN IM_FLOW_STEP.STEP_MODE_CODE IS '關卡模式：SEQUENTIAL 送審後依序簽核／POST_HOC 事後補核（P1 口頭報備、紙本匯入），default SEQUENTIAL';
COMMENT ON COLUMN IM_FLOW_STEP.STATUS         IS '狀態：1 啟用／0 停用，default 1';
COMMENT ON COLUMN IM_FLOW_STEP.CREATE_DATE    IS '建立時間，default SYSDATE';
COMMENT ON COLUMN IM_FLOW_STEP.CREATE_BY      IS '建立人員工號';
COMMENT ON COLUMN IM_FLOW_STEP.UPDATE_DATE    IS '最後更新時間';
COMMENT ON COLUMN IM_FLOW_STEP.UPDATE_BY      IS '最後更新人員工號';


CREATE TABLE IM_APPR (
    APPR_ID             NUMBER(19)      GENERATED BY DEFAULT ON NULL AS IDENTITY,
    DOC_TYPE            VARCHAR2(20)    NOT NULL,
    DOC_ID              VARCHAR2(40)    NOT NULL,
    DOC_VER_NO          NUMBER(5)       DEFAULT 1 NOT NULL,
    FLOW_ID             VARCHAR2(32)    NOT NULL,
    APPR_STATUS_CODE    VARCHAR2(20)    DEFAULT 'PENDING' NOT NULL,
    START_DATE          DATE            DEFAULT SYSDATE NOT NULL,
    CLOSE_DATE          DATE,
    STATUS              NUMBER(1)       DEFAULT 1 NOT NULL,
    CREATE_DATE         DATE            DEFAULT SYSDATE NOT NULL,
    CREATE_BY           VARCHAR2(30)    NOT NULL,
    UPDATE_DATE         DATE,
    UPDATE_BY           VARCHAR2(30),
    CONSTRAINT PK_IM_APPR          PRIMARY KEY (APPR_ID),
    CONSTRAINT CK_IM_APPR_DOC_TYPE CHECK (DOC_TYPE IN ('CR', 'ACCOUNT', 'INSPECTION')),
    CONSTRAINT CK_IM_APPR_APPR_STATUS CHECK (APPR_STATUS_CODE IN ('PENDING', 'APPROVED', 'REJECTED', 'RECALLED', 'CANCELLED')),
    CONSTRAINT CK_IM_APPR_STATUS   CHECK (STATUS IN (0, 1))
);

-- 同一文件同一版次只能有一筆「進行中或已結案」的簽核實例；撤回（RECALLED）或刪除連帶取消
-- （CANCELLED）後，在同版次重新送審會再開一筆（舊資料 17 張撤回單中 16 張於同一 v1 重送），
-- 函式型唯一索引只約束這兩種終局狀態以外的列
CREATE UNIQUE INDEX IND_IM_APPR_01 ON IM_APPR (
    CASE WHEN APPR_STATUS_CODE NOT IN ('RECALLED', 'CANCELLED') THEN DOC_TYPE   END,
    CASE WHEN APPR_STATUS_CODE NOT IN ('RECALLED', 'CANCELLED') THEN DOC_ID     END,
    CASE WHEN APPR_STATUS_CODE NOT IN ('RECALLED', 'CANCELLED') THEN DOC_VER_NO END);
CREATE INDEX IND_IM_APPR_02 ON IM_APPR (DOC_TYPE, DOC_ID);

COMMENT ON TABLE  IM_APPR IS '簽核實例（一次送審）。目的：記錄某文件某版次走過的一輪簽核。來源：送審時由程式產生；舊資料由 applications.json 的 approvals 匯入。主鍵：APPR_ID';
COMMENT ON COLUMN IM_APPR.APPR_ID          IS '流水號（identity 自動產生）';
COMMENT ON COLUMN IM_APPR.DOC_TYPE         IS '文件類型：CR 設備異動申請／ACCOUNT／INSPECTION';
COMMENT ON COLUMN IM_APPR.DOC_ID           IS '文件鍵值；DOC_TYPE = CR 時為 IM_APP.APP_ID';
COMMENT ON COLUMN IM_APPR.DOC_VER_NO       IS '文件版次，對應 IM_APP.CURR_VER_NO 當時的值，default 1';
COMMENT ON COLUMN IM_APPR.FLOW_ID          IS '採用的流程，參照 IM_FLOW.FLOW_ID';
COMMENT ON COLUMN IM_APPR.APPR_STATUS_CODE IS '簽核實例狀態：PENDING 進行中／APPROVED 全數核准／REJECTED 退件／RECALLED 申請人撤回／CANCELLED 文件刪除連帶取消，default PENDING';
