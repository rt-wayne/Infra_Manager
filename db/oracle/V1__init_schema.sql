-- =====================================================================
-- Infra Manager（Java 重寫版）Oracle 19c 初始 schema
-- 依《DB規範_V1_20261002_JLA》16 條命名規範撰寫；業務簡碼 IM_（Infra Manager）。
-- 以具 CREATE TABLE 權限的帳號登入後直接執行，表即建在該帳號（schema）下；
-- S1 骨架建好後整檔搬到 backend/src/main/resources/db/migration/ 交 Flyway。
-- 本檔為 UTF-8；若用 SQL*Plus／SQLcl 手動執行，執行前須將用戶端字元集設成 UTF-8
-- （SQL*Plus：NLS_LANG=TRADITIONAL CHINESE_TAIWAN.AL32UTF8），否則中文會以亂碼寫入。
--
-- 規範以外、本檔自訂的慣例：
--   * CHECK 約束命名 CK_表名_欄名；CHECK／UK 約束欄名過長時取簡稱，總長 ≤ 30
--   * 複合 UK 依前例取最後一個鍵欄命名（UK_IM_APP_EQUIP_SEQ_NO 即 APP_ID＋SEQ_NO）
--   * 子表一律以「表名_ID」identity 為主鍵、原業務鍵設 UK；純鍵值的 _MAP 表與 SYS_PARAM 保留複合主鍵
--   * JSON 欄位後綴 _JSON，型態 CLOB + CHECK (col IS JSON)
--   * 代理鍵用 GENERATED BY DEFAULT ON NULL AS IDENTITY（匯入歷史資料時可指定原值）。
--     匯入時若有指定原值，identity 序號不會跟著前進，匯入完成後須對該表執行
--     ALTER TABLE 表 MODIFY 欄 GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH LIMIT VALUE);
--   * 版次、U 位等整數編號依規範 8 一律 _NO 後綴；時長、大小等數量一律 _QTY 後綴並在欄名帶單位；
--     計次（筆數、次數、人數）一律 _CNT 後綴
--   * 共同欄位 STATUS：1 啟用／0 停用（申請單 0 = 已刪除；使用者 0 = 停用，不提供刪除）
--   * 時間一律 DATE、存台灣當地時間（舊資料的假 UTC 由匯入程式修正）
--   * 人員欄位一律存工號、參照 IM_USER.USER_ID；同表只參照一次時欄名即 USER_ID，
--     參照多次時加角色前綴（APPLY_USER_ID／DELETE_USER_ID）
--   * 純鍵值的多對多關聯表依規範 2 以 _MAP 結尾，並依規範 15 在表說明註明退場條件
--   * 名稱類只存主檔（IM_USER／IM_ROLE／IM_FLOW_STEP／IM_FORM_OPTION），其他表存代碼或鍵值
--   * 匯入歷史資料時 CREATE_DATE／CREATE_BY 由匯入程式寫入原始值，不吃 DEFAULT
--   * 預載資料 CREATE_BY 填 'SYSTEM'
-- 本檔不含任何帳號密碼或連線資訊。
-- =====================================================================


